// Rule chain screens: list + canvas, then double-click a rule node to open its details, close it.
// usage: node probe-rulechain.mjs <base> [extraCssFile]
import { createRequire } from 'module';
const require = createRequire(process.env.FREEHAND_NODE + '/node_modules/x.js');
const { chromium } = require('playwright-core');
const fs = require('fs');
const [base, extraCss] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on('console', (m) => { if (m.type() === 'error') errs.push('CONSOLE ' + m.text().split('\n').slice(0, 4).join(' | ')); });
page.on('pageerror', (e) => errs.push('PAGEERR ' + (e.stack || e.message).split('\n').slice(0, 4).join(' | ')));
page.on('response', (r) => { if (r.url().includes('/api/') && r.status() >= 400) errs.push(`HTTP ${r.status()} ${r.url()}`); });
const step = async (name) => { console.log('==', name, errs.length ? errs.splice(0).join('\n   ') : 'ok'); await page.screenshot({ path: `/tmp/rc-${name}.png` }); };
await page.goto(base + '/login', { waitUntil: 'networkidle' }).catch(() => {});
await page.waitForTimeout(1500);
await page.locator('input[type=email], input[name=username], input[type=text]').first().fill('tenant@thingsboard.org');
await page.locator('input[type=password]').first().fill('tenant');
await page.locator('input[type=password]').first().press('Enter');
await page.waitForTimeout(4000);
await step('login');
await page.goto(base + '/ruleChains', { waitUntil: 'networkidle' }).catch(() => {});
await page.waitForTimeout(3000);
await step('list');
await page.goto(base + '/ruleChains/a8901a50-b9c8-11f1-a5ef-479889dd16ff', { waitUntil: 'networkidle' }).catch(() => {});
await page.waitForTimeout(3000);
if (extraCss) await page.addStyleTag({ content: fs.readFileSync(extraCss, 'utf8') });
await page.waitForTimeout(500);
console.log('nodes', await page.locator('#tb-rulchain-canvas .fc-node').count(), 'edges', await page.locator('#tb-rulchain-canvas path.fc-edge').count(), 'labels', await page.locator('#tb-rulchain-canvas .fc-edge-label').count(), 'lib nodes', await page.locator('.tb-rulechain-library .fc-node').count());
console.log('rulechain box', JSON.stringify(await page.locator('.tb-rulechain').boundingBox()));
await step('canvas');
const node = page.locator('#tb-rulchain-canvas .fc-node').nth(1);
await node.dblclick();
await page.waitForTimeout(2000);
console.log('details', JSON.stringify(await page.evaluate(() => { const c = ng.getComponent(document.querySelector('.tb-rulechain').closest('rule-chain') || document.querySelector('rule-chain')); const sn = document.querySelector('.tb-rulenode-details-sidenav mat-sidenav'); const r = sn && sn.getBoundingClientRect(); return { editing: c && c.isEditingRuleNode, node: c && c.editingRuleNode && c.editingRuleNode.name, sidenav: r && [r.x, r.y, r.width, r.height], vis: sn && getComputedStyle(sn).visibility, text: sn && sn.innerText.slice(0, 150).replace(/\s+/g, ' ') }; })));
console.log('tabs', JSON.stringify(await page.evaluate(() => { const out = []; let e = document.querySelector('.tb-rulenode-details-sidenav tb-rule-node'); while (e && !e.matches('mat-sidenav')) { const r = e.getBoundingClientRect(); const c = getComputedStyle(e); out.push(`${e.tagName}.${String(e.className).slice(0, 30)} ${Math.round(r.y)}/${Math.round(r.height)} ${c.display} ${c.position}`); e = e.parentElement; } return out; })));
await step('node-details');
const close = page.locator(".tb-rulenode-details-sidenav mat-toolbar button").filter({ hasText: "close" }).first();
if (await close.count()) { await close.click(); await page.waitForTimeout(1500); } else console.log('no close button');
console.log('after close editing', await page.evaluate(() => ng.getComponent(document.querySelector('rule-chain')).isEditingRuleNode));
await step('closed');
await browser.close();
