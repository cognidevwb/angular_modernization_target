#!/usr/bin/env python3
"""check-routes — a Playwright spec for every route with a URL, generated.

One test per route: the legacy routes still on AngularJS (their state URL,
`${baseURL}` resolved from the router file, ancestors prefixed) and the
routes moved to the Angular Router (from moves.json). A test opens the URL,
waits for the network to settle, fails on any page error or console error,
and expects the outlet to have rendered something. Route parameters come
from CW_ROUTE_PARAMS (JSON: {"projectPid": "12"}); a route whose parameter
has no value is skipped and says which. Recorded responses (CW_RECORD=1)
land in e2e/cognidev/har/ and replay on later runs, so the check runs
without the backend once recorded. Sessions come from a Playwright storage
state saved after a manual login (CW_APP_STORAGE_STATE): this tool never
handles a password.
"""
import json
import os
import re
import sys

ws = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("CW_WORKDIR", ".")


def load(rel):
    try:
        with open(os.path.join(ws, rel)) as f:
            return json.load(f)
    except Exception:
        return None


shard = load(".cognidev/understand/angular.json") or {}
moves = load(".cognidev/modernization-angular-v2/moves.json") or []
routes = []
base_by_file = {}
for r in shard.get("routes", []):
    if r.get("family") != "angularjs":
        continue
    f = r.get("file", "")
    if f not in base_by_file:
        base_by_file[f] = None
        try:
            src = open(os.path.join(ws, f)).read()
            m = re.search(r"baseURL\s*=\s*([`'\"])(.*?)\1", src)
            base_by_file[f] = m.group(2) if m else None
        except Exception:
            pass
urls = {r["name"]: r.get("url") for r in shard.get("routes", []) if r.get("family") == "angularjs"}
moved = {m["route"]: m for m in moves if m.get("kind", "route") == "route"}
for r in shard.get("routes", []):
    if r.get("family") != "angularjs":
        continue
    name = r["name"]
    if name in moved:
        routes.append({"name": name, "url": "/" + moved[name]["path"].lstrip("/"), "owner": "angular"})
        continue
    own = r.get("url")
    if not own:
        continue
    parts = []
    segs = name.split(".")
    for i in range(1, len(segs)):
        anc = urls.get(".".join(segs[:i]))
        if anc:
            parts.append(anc)
    parts.append(own)
    base = base_by_file.get(r.get("file", "")) or ""
    joined = "".join(p.replace("${baseURL}", base) for p in parts)
    joined = joined.split("?")[0].split("#")[0].replace("//", "/")
    routes.append({"name": name, "url": "/" + joined.strip("/"), "owner": "angularjs"})

out_dir = os.path.join(ws, "e2e", "cognidev")
os.makedirs(os.path.join(out_dir, "har"), exist_ok=True)
slug = lambda s: re.sub(r"[^A-Za-z0-9]+", "-", s).strip("-").lower()
spec = ["// Generated by the playbook (check-routes): one test per route with a URL. Regenerated each run; edit the playbook, not this file.",
        "import { test, expect } from '@playwright/test';",
        "",
        "const params: Record<string, string> = JSON.parse(process.env.CW_ROUTE_PARAMS ?? '{}');",
        "const fill = (u: string) => u.replace(/:([A-Za-z_][A-Za-z0-9_]*)/g, (_m, k) => params[k] ?? `:${k}`);",
        "const record = process.env.CW_RECORD === '1';",
        "",
        "const routes: { name: string; url: string; owner: 'angular' | 'angularjs' }[] = " + json.dumps(routes, indent=2) + ";",
        "",
        "for (const r of routes) {",
        "  test(`${r.owner} · ${r.name} · ${r.url}`, async ({ page }) => {",
        "    const url = fill(r.url);",
        "    const missing = url.match(/:[A-Za-z_][A-Za-z0-9_]*/);",
        "    test.skip(!!missing, `no value for ${missing?.[0]} in CW_ROUTE_PARAMS`);",
        "    const har = `e2e/cognidev/har/${r.owner}-" + "${r.name.replace(/[^A-Za-z0-9]+/g, '-').toLowerCase()}.har`;",
        "    await page.routeFromHAR(har, record ? { update: true } : { notFound: 'fallback' });",
        "    const errors: string[] = [];",
        "    page.on('pageerror', (e) => errors.push(String(e)));",
        "    page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });",
        "    await page.goto(url);",
        "    await page.waitForLoadState('networkidle');",
        "    expect(errors, 'page and console errors').toEqual([]);",
        "    const outlet = r.owner === 'angular' ? page.locator('router-outlet + *, aq-router-outlet router-outlet + *') : page.locator('[ui-view] > *, ui-view > *, [ng-view] > *');",
        "    await expect(outlet.first(), 'the outlet rendered something').toBeVisible();",
        "  });",
        "}",
        ""]
with open(os.path.join(out_dir, "routes.spec.ts"), "w") as f:
    f.write("\n".join(spec))
config = """// Generated by the playbook (check-routes). CW_APP_URL is the running app's origin;
// CW_APP_STORAGE_STATE a Playwright storage state saved after a manual login.
import { defineConfig } from '@playwright/test';

export default defineConfig({
  testDir: '.',
  testMatch: 'routes.spec.ts',
  timeout: 60_000,
  retries: 0,
  reporter: [['json', { outputFile: '../../.cognidev/modernization-angular-v2/route-check.raw.json' }], ['list']],
  use: {
    baseURL: process.env.CW_APP_URL,
    storageState: process.env.CW_APP_STORAGE_STATE || undefined,
    trace: 'retain-on-failure',
  },
});
"""
with open(os.path.join(out_dir, "playwright.config.ts"), "w") as f:
    f.write(config)
n_ng = sum(1 for r in routes if r["owner"] == "angular")
print(f"check-routes: {len(routes)} route(s) with a URL in e2e/cognidev/routes.spec.ts — {n_ng} on the Angular Router, {len(routes) - n_ng} still on AngularJS")
